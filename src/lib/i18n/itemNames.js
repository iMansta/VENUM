/**
 * Get item name in specified language
 * @param {string} itemId - The item ID to translate
 * @param {string} language - 'pt' for Portuguese, 'en' for English (default)
 * @returns {string} The translated item name or the original ID if not found
 */
export const getItemName = (itemId, language = 'pt') => {
  const translation = itemTranslations[itemId];
  if (!translation) {
    return itemId; // Return original ID if not found
  }
  return translation[language] || translation.en || itemId;
};

/**
 * Get item metadata
 * @param {string} itemId - The item ID
 * @returns {object} Item metadata including category, tier, etc.
 */
export const getItemMetadata = (itemId) => {
  return itemTranslations[itemId] || {
    category: 'unknown',
    tier: 0,
  };
};

/**
 * Get item tier from ID
 * @param {string} itemId - The item ID
 * @returns {number} The tier number (0 if not found)
 */
export const getItemTier = (itemId) => {
  const metadata = getItemMetadata(itemId);
  return metadata.tier || 0;
};

/**
 * Get item category from ID
 * @param {string} itemId - The item ID
 * @returns {string} The category name
 */
export const getItemCategory = (itemId) => {
  const metadata = getItemMetadata(itemId);
  return metadata.category || 'unknown';
};

/**
 * Format item name with tier and enchantment
 * @param {string} itemId - The item ID
 * @param {number} enchantment - Enchantment level (0-4)
 * @param {string} language - Language code
 * @returns {string} Formatted item name
 */
export const formatItemName = (itemId, enchantment = 0, language = 'pt') => {
  const baseName = getItemName(itemId, language);
  if (enchantment > 0) {
    const enchantmentSymbol = '@'.repeat(enchantment);
    return `${baseName}${enchantmentSymbol}`;
  }
  return baseName;
};
